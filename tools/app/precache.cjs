// Writes sw-files.js: every file the game needs offline (pages, code, fonts, pixel art, voice).
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '../..');
const list = ['./', 'index.html', 'test.html', 'intro.html', 'manifest.webmanifest', 'manifest-test.webmanifest', 'css/style.css', 'audio/hymne.mp3'];
const walk = (d) => fs.readdirSync(path.join(root, d), { withFileTypes: true }).forEach((e) => {
  const rel = `${d}/${e.name}`;
  if (e.isDirectory()) walk(rel); else list.push(rel);
});
['src', 'assets/fonts', 'assets/pixel', 'assets/voice', 'assets/app'].forEach(walk);
fs.writeFileSync(path.join(root, 'sw-files.js'), `// generated by tools/app/precache.cjs\nself.PRECACHE = ${JSON.stringify(list, null, 0)};\n`);
console.log(list.length, 'files');
