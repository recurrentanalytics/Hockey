// Writes sw-files.js: every file the game needs offline (pages, code, fonts, pixel art, voice).
// With --check nothing is written: exit code 1 if sw-files.js no longer lists the same files
// (used by tests/precache.test.mjs and CI).
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '../..');
const list = ['./', 'index.html', 'test.html', 'intro.html', 'manifest.webmanifest', 'manifest-test.webmanifest', 'css/style.css', 'audio/hymne.mp3'];
const walk = (d) => fs.readdirSync(path.join(root, d), { withFileTypes: true }).forEach((e) => {
  const rel = `${d}/${e.name}`;
  if (e.isDirectory()) walk(rel); else list.push(rel);
});
['src', 'assets/fonts', 'assets/pixel', 'assets/voice', 'assets/app'].forEach(walk);
const file = path.join(root, 'sw-files.js');
if (process.argv.includes('--check')) {
  const m = fs.existsSync(file) && /self\.PRECACHE = (\[[^\]]*\])/.exec(fs.readFileSync(file, 'utf8'));
  const current = m ? JSON.parse(m[1]) : [];
  const missing = list.filter((f) => !current.includes(f)), stale = current.filter((f) => !list.includes(f));
  if (missing.length || stale.length) {
    console.log(`sw-files.js is out of date: ${missing.length} missing, ${stale.length} stale. Run: node tools/app/precache.cjs`);
    for (const f of missing) console.log(`  missing  ${f}`);
    for (const f of stale) console.log(`  stale    ${f}`);
    process.exit(1);
  }
  console.log(`sw-files.js is up to date (${current.length} files)`);
  process.exit(0);
}
fs.writeFileSync(file, `// generated by tools/app/precache.cjs\nself.PRECACHE = ${JSON.stringify(list, null, 0)};\n`);
console.log(list.length, 'files');
